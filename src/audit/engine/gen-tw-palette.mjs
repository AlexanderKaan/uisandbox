#!/usr/bin/env node
/**
 * gen-tw-palette — write src/tw-palette.mjs from the palettes Tailwind SHIPS.
 *
 *   node scripts/gen-tw-palette.mjs            # fetch both from unpkg, write the module
 *   node scripts/gen-tw-palette.mjs --check    # exit 1 when the module is out of step
 *
 * The audit reads Tailwind class names — `bg-indigo-600` — as colour usages by
 * NAME. To compare them, count them or call one of them the brand it needs the
 * colour behind the name, and that colour comes, in order, from: the repo's own
 * overrides (`--color-*` in @theme / :root), the Tailwind build INSTALLED in the
 * repo (node_modules — the exact version's numbers), and — only when neither is
 * there: a shallow clone, a browser drop, a Phoenix app whose Tailwind is a
 * standalone binary — the defaults Tailwind ships for the generation the repo's
 * CSS says it is on (`@import "tailwindcss"` → v4, `@tailwind base` → v3).
 *
 * The defaults are NOT hand-typed. A table of 242 numbers where every entry is
 * an independent chance to be silently wrong is the failure this file exists
 * to avoid; the module is generated from the two files Tailwind publishes,
 * pinned by version, and the check mode holds it to them. v3 ships hex; v4
 * ships oklch() and is kept as oklch — it resolves through the same transform
 * every other oklch() in a codebase does, so the swatch we paint is the swatch
 * the browser paints.
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'

const HERE = dirname(fileURLToPath(import.meta.url))
const OUT = join(HERE, '../src/tw-palette.mjs')
const CHECK = process.argv.includes('--check')

/* Pinned. Bump deliberately; the module records what it was built from. */
export const SOURCES = {
  v3: { version: '3.4.17', url: 'https://unpkg.com/tailwindcss@3.4.17/lib/public/colors.js' },
  v4: { version: '4.3.3', url: 'https://unpkg.com/tailwindcss@4.3.3/theme.css' },
}

async function fetchText(url) {
  const res = await fetch(url)
  if (!res.ok) throw new Error(`${url} → ${res.status}`)
  return res.text()
}

/** v3 — `colors.js` is CommonJS `module.exports = { hue: { shade: hex } }` with
 *  deprecated aliases as getters. Read the literals, not the module: no eval. */
function parseV3(js) {
  const out = {}
  // top-level literal colours: `white: "#fff"`, `transparent: "transparent"`
  for (const m of js.matchAll(/^\s{4}([a-z]+):\s*"(#[0-9a-f]{3,8}|transparent|currentColor|inherit)"/gim)) {
    if (/^#/.test(m[2])) out[m[1]] = m[2].toLowerCase()
  }
  // ramps: `    indigo: {\n        50: "#eef2ff", …`
  for (const m of js.matchAll(/^\s{4}([a-z]+):\s*\{([^}]+)\}/gm)) {
    for (const s of m[2].matchAll(/(\d{2,3}):\s*"(#[0-9a-f]{3,8})"/gi)) out[`${m[1]}-${s[1]}`] = s[2].toLowerCase()
  }
  return out
}

/** v4 — `theme.css` declares the palette as `--color-<name>: oklch(…)`. */
function parseV4(css) {
  const out = {}
  for (const m of css.matchAll(/--color-([a-z]+(?:-\d{2,3})?)\s*:\s*([^;]+);/g)) {
    const v = m[2].trim()
    if (/^oklch\(|^#/.test(v)) out[m[1]] = v
  }
  return out
}

function render(v3, v4) {
  const rows = (o) => Object.entries(o).map(([k, v]) => `  '${k}': '${v}',`).join('\n')
  return `/* GENERATED by scripts/gen-tw-palette.mjs — do not edit.
 * Tailwind's default colour palettes, read from the files Tailwind publishes:
 *   v3 ← tailwindcss@${SOURCES.v3.version} lib/public/colors.js (hex)
 *   v4 ← tailwindcss@${SOURCES.v4.version} theme.css (oklch, kept as shipped)
 * The audit uses these ONLY when the repo carries neither its own --color-*
 * overrides nor an installed Tailwind build — see colorspace.mjs resolvePalette. */
export const TW_DEFAULT_VERSIONS = { v3: '${SOURCES.v3.version}', v4: '${SOURCES.v4.version}' }

export const TW_DEFAULTS = {
  v3: {
${rows(v3)}
  },
  v4: {
${rows(v4)}
  },
}
`
}

const [v3src, v4src] = await Promise.all([fetchText(SOURCES.v3.url), fetchText(SOURCES.v4.url)])
const v3 = parseV3(v3src), v4 = parseV4(v4src)
for (const [gen, o] of [['v3', v3], ['v4', v4]]) {
  const n = Object.keys(o).length
  if (n < 240) throw new Error(`${gen}: parsed only ${n} colours — the upstream file changed shape`)
  for (const probe of ['indigo-600', 'blue-500', 'gray-500', 'red-500', 'white']) if (!o[probe]) throw new Error(`${gen}: missing ${probe}`)
}
const next = render(v3, v4)
let current = null
try { current = readFileSync(OUT, 'utf8') } catch { /* first run */ }
if (CHECK) {
  if (current !== next) { console.error(`gen-tw-palette: src/tw-palette.mjs is out of step with the pinned sources — run node scripts/gen-tw-palette.mjs`); process.exit(1) }
  console.log(`gen-tw-palette: current (v3 ${Object.keys(v3).length} · v4 ${Object.keys(v4).length} colours)`)
} else {
  writeFileSync(OUT, next)
  console.log(`gen-tw-palette: wrote ${OUT} (v3 ${Object.keys(v3).length} · v4 ${Object.keys(v4).length} colours)`)
}
